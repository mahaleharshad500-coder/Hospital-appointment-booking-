using HospitalAppointmentSystem.Data;
using Microsoft.EntityFrameworkCore;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllersWithViews();
builder.Services.AddDbContext<HospitalContext>(o => o.UseSqlite(builder.Configuration.GetConnectionString("HospitalConnection")));
var app = builder.Build();
using(var scope=app.Services.CreateScope()) scope.ServiceProvider.GetRequiredService<HospitalContext>().Database.EnsureCreated();
app.UseStaticFiles();
app.UseRouting();
app.MapControllerRoute(name:"default",pattern:"{controller=Home}/{action=Index}/{id?}");
app.Run();
